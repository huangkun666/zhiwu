"""Run python client/test/browser/tutor_history.py -v after npm run build.

Uses the same isolated fixture and optional ZHIWU_APK_CDP, ADB, ANDROID_SERIAL
variables as tutor_retrieval.py. The APK test requires a fresh, empty test library.
For an APK upgrade over the exact unmodified legacy fixture generated by this test,
set ZHIWU_HISTORY_UPGRADE=1; every seeded title and message is checked before use.
Desktop uses the existing production dist; standalone is built into the disposable
fixture. Set ZHIWU_HISTORY_DEV=1 to exercise Vite dev servers during development.
"""
from collections import Counter
from contextlib import closing
import json
import os
from pathlib import Path
import re
import sqlite3
import subprocess
import unittest
from playwright.sync_api import expect

from tutor_retrieval import TutorBrowserTest


OLD = "研读记录 000 早期光学笔记"
RENAMED = "台架交接复盘"
USER_KEY = "only-user-amber-71"
ASSISTANT_KEY = "only-tutor-mica-52"
FOLLOWUP = "请继续刚才的讨论"
ANSWER = "已接上早期光学实验，对照值为 41。"
DUPLICATE = "研读记录 同名实验"
REF = dict(id="history-ref", title="临时参考笔记", content="现场工作记录。",
           created_at="2023-01-01T00:00:00.000Z", updated_at="2023-01-01T00:00:00.000Z")


def history_fixture():
    sessions, messages = [], {}
    for n in range(67):
        sid = f"legacy-chat-{n:03d}"
        title = OLD if n == 0 else DUPLICATE if n in (8, 9) else f"研读记录 {n:03d}"
        # 60 rows share one timestamp, spanning a page boundary in either sort direction.
        ts = f"2023-01-{min(8, n + 1):02d}T12:00:00.000Z"
        sessions.append(dict(id=sid, title=title, mode="qa", note_ids=[REF["id"]] if n == 1 else [],
                             created_at=ts, updated_at=ts))
        question = USER_KEY if n == 1 else f"旧问题 {n:03d}"
        reply = ASSISTANT_KEY if n == 2 else f"旧答复 {n:03d}"
        messages[sid] = [dict(id=f"{sid}-{role}", session_id=sid, role=role, content=content,
                              created_at=ts.replace("00.000Z", f"0{i}.000Z"))
                         for i, (role, content) in enumerate([("user", question), ("assistant", reply)])]
    return sessions, messages


class ContinueModel:
    def __init__(self):
        self.errors = []
        self.calls = 0

    def respond(self, body):
        messages = body["messages"]
        assert messages[-1]["content"] == FOLLOWUP, messages[-1]
        assert any(m["role"] == "user" and m["content"] == "旧问题 000" for m in messages)
        assert any(m["role"] == "assistant" and m["content"] == "旧答复 000" for m in messages)
        self.calls += 1
        return ANSWER


class TutorHistoryTest(TutorBrowserTest):
    fixture_args = () if os.environ.get("ZHIWU_HISTORY_DEV") else ("--built-history",)

    def seed_sqlite(self, sessions, messages):
        path = Path(self.origins["database"]).resolve()
        self.assertTrue(path.parent.parent.name.startswith(".tutor-browser-"), "Only seed our temporary SQLite DB")
        with closing(sqlite3.connect(path.as_uri() + "?mode=rw", uri=True)) as db, db:
            self.assertEqual(db.execute("SELECT count(*) FROM tutor_sessions").fetchone()[0], 0)
            db.execute("INSERT INTO notes(id,title,content,created_at,updated_at) "
                       "VALUES(:id,:title,:content,:created_at,:updated_at)", REF)
            db.executemany("INSERT INTO tutor_sessions(id,title,mode,note_ids,created_at,updated_at) "
                           "VALUES(:id,:title,:mode,:note_ids,:created_at,:updated_at)",
                           [dict(s, note_ids=json.dumps(s["note_ids"])) for s in sessions])
            db.executemany("INSERT INTO tutor_messages(id,session_id,role,content,created_at) "
                           "VALUES(:id,:session_id,:role,:content,:created_at)",
                           [m for thread in messages.values() for m in thread])

    def seed_indexeddb(self, page, sessions, messages, upgrade):
        page.evaluate("""async ([sessions, messages, note, upgrade]) => {
            const open = indexedDB.open('zhiwu_on_device_db');
            const db = await new Promise((resolve, reject) => {
                open.onsuccess = () => resolve(open.result); open.onerror = () => reject(open.error);
            });
            try {
                const tx = db.transaction('kv', 'readwrite');
                const store = tx.objectStore('kv');
                const read = store.get('zhiwu_state_v1');
                const done = new Promise((resolve, reject) => {
                    tx.oncomplete = resolve; tx.onabort = () => reject(Error('Fixture library does not match expected input'));
                });
                read.onsuccess = () => {
                    const state = read.result;
                    if (upgrade) {
                        if (state?.notes?.length !== 1 || state.notes[0].id !== note.id ||
                            state.tutorSessions.length !== sessions.length ||
                            Object.keys(state.tutorMessages).length !== sessions.length ||
                            !sessions.every(s => state.tutorSessions.some(old => old.id === s.id &&
                                old.title === s.title && old.updated_at === s.updated_at) &&
                                JSON.stringify(state.tutorMessages[s.id]) === JSON.stringify(messages[s.id]))) tx.abort();
                        return;
                    }
                    if (!state || state.notes.length || state.tutorSessions.length) { tx.abort(); return; }
                    store.put({...state, notes:[{...note, tags:[], source_type:'markdown', word_count:7,
                        chat_excerpts:[], is_pinned:0}], tutorSessions:sessions, tutorMessages:messages}, 'zhiwu_state_v1');
                };
                await done;
            } finally { db.close(); }
        }""", [sessions, messages, REF, upgrade])

    def exercise(self, page, platform):
        mobile = platform != "desktop"
        history = page.get_by_role("dialog", name="历史对话", exact=True) if mobile else page
        tutor = page.get_by_role("button", name="助教", exact=True)
        search = history.get_by_role("searchbox", name="搜索历史对话", exact=True)
        trigger = page.get_by_role("button", name="历史对话", exact=True)
        conversation = page.get_by_role("region", name="对话消息", exact=True)
        sessions, messages = history_fixture()
        self.model.witness = model = ContinueModel()
        page.set_default_timeout(15000)

        if platform == "apk":
            self.assertEqual(page.evaluate("window.Capacitor?.getPlatform()"), "android")
            page.goto(page.evaluate("location.origin"))
        else:
            page.goto(self.origins[platform])
        page.get_by_role("button", name="设置", exact=True).click()
        page.get_by_role("button", name=re.compile("^本地模型")).click()
        page.locator("label", has_text="API Base URL").locator("..").locator("input").fill(self.model_origin)
        page.get_by_role("button", name="保存并启用", exact=True).click()
        expect(page.get_by_text("已保存", exact=True)).to_be_visible()
        if mobile:
            self.seed_indexeddb(page, sessions, messages, platform == "apk" and
                                bool(os.environ.get("ZHIWU_HISTORY_UPGRADE")))
        else:
            self.seed_sqlite(sessions, messages)
        origin = page.evaluate("location.origin")
        page.goto(origin)
        tutor.click()
        expect(conversation).to_be_visible()

        def show():
            if mobile and not history.is_visible():
                trigger.click()
                expect(history).to_be_visible()
            expect(search).to_be_visible()

        def row(title):
            return history.get_by_role("button", name=title, exact=True)

        def named_action(verb, title):
            return history.get_by_role("button", name=f"{verb}「{title}」", exact=True)

        def find(query, title):
            search.fill(query)
            expect(row(title)).to_be_visible()

        def all_rows():
            return history.get_by_role("button", name=re.compile("^研读记录"))

        if mobile:
            panel = page.locator('[aria-label="对话消息"]')
            rect = panel.bounding_box()
            show()
            # A modal can set aria-hidden/inert on its background; the chat still keeps its dimensions.
            for key in ("x", "y", "width", "height"):
                self.assertAlmostEqual(rect[key], panel.bounding_box()[key], delta=2)
            history.get_by_role("button", name="关闭历史对话", exact=True).click()
            expect(history).to_be_hidden()
            self.assertAlmostEqual(panel.bounding_box()["height"], rect["height"], delta=2)
        show()
        expect(all_rows()).to_have_count(30)
        expect(row(OLD)).to_have_count(0)

        if not mobile:
            # Return an older request *after* the new query, then fail one real page fetch and retry.
            delayed = []
            def hold(route):
                delayed.append(route)
            slow = "**/api/tutor/history?q=" + USER_KEY
            page.route(slow, hold)
            with page.expect_request(slow):
                search.fill(USER_KEY)
            find(ASSISTANT_KEY, "研读记录 002")
            self.assertEqual(len(delayed), 1)
            with page.expect_response(slow) as late:
                delayed[0].fulfill(response=page.request.get(delayed[0].request.url))
            self.assertEqual(late.value.json()["items"][0]["id"], "legacy-chat-001")
            page.evaluate("() => new Promise(r => requestAnimationFrame(() => requestAnimationFrame(r)))")
            expect(row("研读记录 002")).to_be_visible()
            expect(row("研读记录 001")).to_have_count(0)
            page.unroute(slow, hold)
            page.route(slow, lambda route: route.fulfill(status=503, json={"error":"临时测试故障"}), times=1)
            search.fill(USER_KEY)
            history.get_by_role("button", name="重试", exact=True).click()
            expect(row("研读记录 001")).to_be_visible()

        # Search older title, user text and assistant text from the first page.
        for query, title in [(OLD, OLD), (USER_KEY, "研读记录 001"), (ASSISTANT_KEY, "研读记录 002")]:
            find(query, title)
            expect(all_rows()).to_have_count(1)
        search.fill(DUPLICATE)
        expect(row(DUPLICATE)).to_have_count(2)
        search.fill("")
        expect(all_rows()).to_have_count(30)
        more = history.get_by_role("button", name="加载更多", exact=True)
        more.click()
        expect(all_rows()).to_have_count(60)
        more.click()
        expect(all_rows()).to_have_count(67)
        self.assertEqual(Counter(all_rows().evaluate_all("rows => rows.map(r => r.getAttribute('aria-label') || r.innerText.trim())")),
                         Counter(s["title"] for s in sessions))
        expect(more).to_be_hidden()
        row(OLD).click()
        expect(conversation.get_by_text("旧答复 000", exact=True)).to_be_visible()
        page.locator("textarea").fill(FOLLOWUP)
        page.get_by_role("button", name="发送消息", exact=True).click()
        expect(conversation.get_by_text(ANSWER, exact=True)).to_be_visible(timeout=20000)
        self.assertEqual(model.errors, [])
        self.assertEqual(model.calls, 1)

        show()
        find(OLD, OLD)
        named_action("重命名", OLD).click()
        page.get_by_role("textbox", name="对话名称").fill(RENAMED)
        page.get_by_role("button", name="保存", exact=True).click()
        expect(page.get_by_role("textbox", name="对话名称")).to_be_hidden()
        show()
        search.fill(OLD)
        expect(history.get_by_text("无匹配对话", exact=True)).to_be_visible()
        find(RENAMED, RENAMED)

        victim = "研读记录 002"
        find(ASSISTANT_KEY, victim)
        named_action("删除", victim).click()
        page.get_by_role("button", name="取消", exact=True).click()
        expect(row(victim)).to_be_visible()
        named_action("删除", victim).click()
        page.get_by_role("button", name="确认删除", exact=True).click()
        expect(page.get_by_role("button", name="确认删除", exact=True)).to_be_hidden()
        show()
        search.fill(ASSISTANT_KEY)
        expect(history.get_by_text("无匹配对话", exact=True)).to_be_visible()

        # Reopen the app and verify the edits plus the entire continued conversation from persistent storage.
        page.goto(origin)
        tutor.click()
        show()
        search.fill("")
        expect(row(RENAMED)).to_have_count(1)
        more.click()
        expect(all_rows()).to_have_count(59)
        more.click()
        expect(more).to_be_hidden()
        expect(all_rows()).to_have_count(65)
        titles = Counter(all_rows().evaluate_all("rows => rows.map(r => r.getAttribute('aria-label') || r.innerText.trim())"))
        self.assertEqual(titles, Counter(s["title"] for s in sessions if s["title"] not in (OLD, victim)))
        find(USER_KEY, "研读记录 001")
        search.fill(ASSISTANT_KEY)
        expect(history.get_by_text("无匹配对话", exact=True)).to_be_visible()
        search.fill(OLD)
        expect(history.get_by_text("无匹配对话", exact=True)).to_be_visible()
        find(ANSWER, RENAMED)
        row(RENAMED).click()
        for text in ("旧问题 000", "旧答复 000", FOLLOWUP, ANSWER):
            expect(conversation.get_by_text(text, exact=True)).to_be_visible()

        # Delete the currently open thread, including its draft and selected reference.
        show()
        active_victim = "研读记录 001"
        find(USER_KEY, active_victim)
        row(active_victim).click()
        expect(conversation.get_by_text(USER_KEY, exact=True)).to_be_visible()
        expect(page.get_by_role("button", name="参考笔记 (1)", exact=True)).to_be_visible()
        page.locator("textarea").fill("此临时草稿属于即将删除的会话")
        show()
        find(USER_KEY, active_victim)
        named_action("删除", active_victim).click()
        page.get_by_role("button", name="确认删除", exact=True).click()
        expect(page.get_by_role("button", name="确认删除", exact=True)).to_be_hidden()
        show()
        search.fill(USER_KEY)
        expect(history.get_by_text("无匹配对话", exact=True)).to_be_visible()
        if mobile:
            history.get_by_role("button", name="关闭历史对话", exact=True).click()
        expect(conversation.get_by_text(USER_KEY, exact=True)).to_have_count(0)
        expect(conversation.get_by_text("旧答复 001", exact=True)).to_have_count(0)
        expect(page.locator("textarea")).to_have_value("")
        expect(page.get_by_role("button", name=re.compile("参考笔记"))).to_have_count(0)
        expect(page.get_by_role("button", name="对话设置", exact=True)).to_have_count(0)
        show()
        find(RENAMED, RENAMED)
        row(RENAMED).click()
        expect(conversation.get_by_text(ANSWER, exact=True)).to_be_visible()

    def test_desktop_sqlite(self):
        with self.browser.new_context(viewport={"width": 1440, "height": 960}, service_workers="block") as context:
            self.exercise(context.new_page(), "desktop")

    def test_standalone_indexeddb(self):
        with self.browser.new_context(viewport={"width": 390, "height": 844}, is_mobile=True,
                                      service_workers="block") as context:
            self.exercise(context.new_page(), "standalone")

    @unittest.skipUnless(os.environ.get("ZHIWU_APK_CDP"), "Requires a disposable empty debug APK")
    def test_android_apk(self):
        adb = [os.environ.get("ADB", "adb"), "-s", os.environ["ANDROID_SERIAL"]]
        port = self.model.server_port
        subprocess.run(adb + ["reverse", f"tcp:{port}", f"tcp:{port}"], check=True)
        self.addCleanup(subprocess.run, adb + ["reverse", "--remove", f"tcp:{port}"])
        self.exercise(self.apk_page(), "apk")


if __name__ == "__main__":
    unittest.main()
